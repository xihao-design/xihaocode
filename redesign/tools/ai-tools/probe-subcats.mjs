/* 第二轮分析：改成「互斥的主功能桶」再数一遍。
   ------------------------------------------------------------
   第一轮用的是「一个子类一组关键词，命中即属于该子类」，结果是子类之间大量重叠：
     audio：「语音合成/配音」与「语音克隆」命中了完全相同的 5 条
     chatbot：三个子类全部命中同样的 10 条
     coding：「IDE/编辑器」与「代码补全插件」都是 9 条
   这等于同一批工具产出 2–3 个几乎一样的页面 —— 站内既有规矩明确反对这件事
   （content/tags.json 的注释：「分类切不出来的角度才值得单独做一页」）。

   所以这一轮改成：**每个条目只归入一个桶**，按优先级顺序取第一个命中的桶，
   并且桶的关键词按「越具体越靠前」排列。这样：
     · 同一父类下不会出现重复条目（也就不可能产出重复内容）
     · 每个桶的条目数就是它真实的规模，够不够门槛一眼可见
   ============================================================ */
import fs from 'node:fs';
import path from 'node:path';

