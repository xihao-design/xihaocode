const all = [];
for (const c of fs.readdirSync(ROOT)) {
  for (const f of fs.readdirSync(path.join(ROOT, c)).filter(x => x.endsWith('.json'))) {
    all.push({ cat: c, ...JSON.parse(fs.readFileSync(path.join(ROOT, c, f), 'utf8')) });
  }
}

