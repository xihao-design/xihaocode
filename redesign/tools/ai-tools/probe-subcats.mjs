const corpus = t => [t.nameZh, t.name, t.vendor, t.tagline, t.desc, ...(t.features || []), ...(t.howto || [])]
  .filter(Boolean).join(' ').toLowerCase();

const MIN = 4;
let thin = 0, live = 0;
for (const [cat, buckets] of Object.entries(BUCKETS)) {
  const list = all.filter(t => t.cat === cat);
  if (!list.length) continue;
  const assign = new Map(buckets.map(([n]) => [n, []]));
  assign.set('（无主功能桶命中）', []);
  for (const t of list) {
    const text = corpus(t);
    let put = '（无主功能桶命中）';
    for (const [n, kws] of buckets) {
      if (kws.some(k => text.includes(String(k).toLowerCase()))) { put = n; break; }
    }
    assign.get(put).push(t.slug);
  }
  console.log(`${cat}（${list.length} 条）`);
  for (const [n, arr] of assign) {
    if (!arr.length) continue;
    const ok = arr.length >= MIN;
    if (ok) live++; else thin++;
    console.log(`  ${ok ? '✅' : '  '} ${n.padEnd(20)} ${String(arr.length).padStart(3)}  ${arr.length <= 6 ? arr.join(', ') : arr.slice(0, 6).join(', ') + '…'}`);
  }
  console.log('');
}
